# Keep the load order: when two packages export the same function, the last one loaded wins.
Sys.setenv(TZ='GMT')
knitr::opts_chunk$set(echo = TRUE)
options(tinytex.verbose = TRUE)
if (!require('readxl')) install.packages('readxl'); library('readxl')
if (!require('writexl')) install.packages('writexl'); library('writexl')
if (!require('lubridate')) install.packages('lubridate'); library('lubridate')
if (!require('stringr')) install.packages('stringr'); library('stringr')
if (!require('dplyr')) install.packages('dplyr'); library('dplyr')
if (!require('data.table')) install.packages('data.table'); library('data.table')
if (!require('tidyverse')) install.packages('tidyverse'); library('tidyverse')
if (!require('phrutils')) remotes::install_github("impact-initiatives/phrutils"); library('phrutils')
if (!require('phrindicators')) remotes::install_github("impact-initiatives/phrindicators"); library('phrindicators')
if (!require('remotes')) install.packages('remotes'); library('remotes')
if (!require('robotoolbox')) remotes::install_gitlab("dickoa/robotoolbox"); library('robotoolbox')
if (!require('openxlsx')) install.packages('openxlsx'); library('openxlsx')
if (!require('sjstats')) install.packages('sjstats'); library('sjstats')
if (!require('humind')) devtools::install_github("impact-initiatives-hppu/humind"); library('humind')
if (!require('hypegrammaR')) remotes::install_github("mabafaba/hypegrammaR"); library('hypegrammaR')
if (!require('composr')) remotes::install_github("mabafaba/composr"); library('composr')
if (!require('presentresults')) remotes::install_github("impact-initiatives/presentresults"); library('presentresults')
if (!require('analysistools')) remotes::install_github("impact-initiatives/analysistools"); library('analysistools')
if (!require('impactR.utils')) remotes::install_github("gnoblet/impactR.utils"); library('impactR.utils')

